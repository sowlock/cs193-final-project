package tetris.model;

/** the five shapes */
public enum Tetromino {
    I(new int[][][] {
        {{0, 0}, {0, 1}, {0, 2}, {0, 3}},
        {{0, 0}, {1, 0}, {2, 0}, {3, 0}}
    }),
    S(new int[][][] {
        {{0, 1}, {0, 2}, {1, 0}, {1, 1}},
        {{0, 0}, {1, 0}, {1, 1}, {2, 1}}
    }),
    O(new int[][][] {
        {{0, 0}, {0, 1}, {1, 0}, {1, 1}}
    }),
    L(new int[][][] {
        {{0, 2}, {1, 0}, {1, 1}, {1, 2}},
        {{0, 0}, {1, 0}, {2, 0}, {2, 1}},
        {{0, 0}, {0, 1}, {0, 2}, {1, 0}},
        {{0, 0}, {0, 1}, {1, 1}, {2, 1}}
    }),
    Z(new int[][][] {
        {{0, 0}, {0, 1}, {1, 1}, {1, 2}},
        {{0, 1}, {1, 0}, {1, 1}, {2, 0}}
    });
}
